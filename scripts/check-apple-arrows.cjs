const fs = require('fs'), ts = require('typescript'), assert = require('node:assert/strict')
require.extensions['.ts'] = (module, file) => module._compile(ts.transpileModule(fs.readFileSync(file, 'utf8'), {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true },
}).outputText, file)
const { createAppleArrows, getAnimatedFoodOffset } = require('../src/assets/trainingArena/appleArrows.ts')
const { isPlayableCell } = require('../src/engine/field/fieldGeometry.ts')
const arrows = createAppleArrows(), [horizontal, vertical] = arrows.group.children
const THREE = require('three')
horizontal.geometry.computeBoundingBox()
const arrowSize=horizontal.geometry.boundingBox.getSize(new THREE.Vector3())
assert(arrowSize.y>.8 && arrowSize.y<1 && arrowSize.x>.8 && arrowSize.x<1,'outline fits cell-sized bounds')
const outline = new THREE.Mesh(horizontal.geometry, horizontal.material)
const ray = new THREE.Raycaster(new THREE.Vector3(0,0,1), new THREE.Vector3(0,0,-1))
assert.equal(ray.intersectObject(outline).length,0,'arrow interior must be empty')
ray.ray.origin.set(-.46,.11,1)
assert(ray.intersectObject(outline).length>0,'outline must remain visible')
ray.ray.origin.set(-.46,.073333,1)
assert.equal(ray.intersectObject(outline).length,0,'dash gaps must be empty')
arrows.update([0, 0, 4], [22, 12], { x: 12, y: -5 }, true)
assert(arrows.group.visible && horizontal.visible && vertical.visible)
assert.deepEqual(horizontal.position.toArray(), [1, 0, .035])
assert.deepEqual(vertical.position.toArray(), [0, -1, .035])
assert.equal(horizontal.rotation.z, 0); assert.equal(vertical.rotation.z, -Math.PI / 2)
const previous = horizontal.scale.x
// Head moves between cells while the committed grid cell remains unchanged.
arrows.update([.5, 0, 8], [22, 12], getAnimatedFoodOffset([.5,0,8],[34,7]), true)
assert(horizontal.scale.x<previous, 'length must change during the animated half-step')
arrows.update([.25, .1, 8], [22, 12], { x: 11, y: -5 }, true)
assert.equal(horizontal.position.x, 1.25)
assert.equal(horizontal.position.y, .1)
assert.equal(horizontal.position.z, .035, 'arrows stay on the floor during head lift')
assert(horizontal.scale.x < previous)
arrows.update([0, 0], [22, 12], { x: -20, y: 20 }, true)
assert.equal(horizontal.rotation.z, Math.PI)
assert.equal(vertical.rotation.z, Math.PI / 2)
assert.equal(horizontal.scale.x, vertical.scale.x)
assert(horizontal.scale.x < 1 && vertical.scale.x < 1, 'each arrow fits one neighbouring cell')
arrows.update([0,0], [22,12], {x:1,y:42}, true)
assert(vertical.scale.x/horizontal.scale.x>4, 'near and far distances must have visibly different lengths')
arrows.update([0, 0], [22, 12], { x: 0, y: 5 }, true)
assert(!horizontal.visible && vertical.visible)
// At a clipped corner, find distinct playable neighbouring cells.
const corner = require('../src/engine/field/fieldGeometry.ts').getPlayableCells()[0]
arrows.update([0, 0], corner, { x: -10, y: -10 }, true)
assert(horizontal.visible && vertical.visible)
assert.notDeepEqual(horizontal.position.toArray(), vertical.position.toArray())
for (const arrow of [horizontal, vertical]) assert(isPlayableCell(corner[0] + arrow.position.x, corner[1] + arrow.position.y))
arrows.update([0, 0], [22, 12], { x: 5, y: 5 }, false)
assert(!arrows.group.visible)
arrows.update([0, 0], [22, 12], null, true)
assert(!arrows.group.visible)
horizontal.geometry.dispose(); horizontal.material.dispose()
console.log('PASS: flat arrows, per-axis directions, distance lengths, continuous following, no lift, zero axis, corner neighbours and mode visibility.')
