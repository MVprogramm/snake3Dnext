const fs = require('fs'), ts = require('typescript'), assert = require('node:assert/strict')
const THREE = require('three')
require.extensions['.ts'] = (module, file) => module._compile(ts.transpileModule(fs.readFileSync(file, 'utf8'), {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
}).outputText, file)
const { FollowingCamera } = require('../src/assets/trainingArena/followingCamera.ts')
const fixed = new THREE.PerspectiveCamera(90, 1, .1, 200)
fixed.position.set(0, 0, 10); fixed.lookAt(0, 0, 0); fixed.updateMatrixWorld(true)
const view = { width: 100, height: 100, imageWidth: 100, imageHeight: 100, panX: 0, panY: 0 }
const inside = [new THREE.Vector3(-8, -8, 0), new THREE.Vector3(8, 8, 0)]
const outside = [new THREE.Vector3(-12, -8, 0), new THREE.Vector3(12, 8, 0)]
const head = new THREE.Vector3(9, 7, 0)
const follow = new FollowingCamera()
const originalPosition = fixed.position.clone(), originalProjection = fixed.projectionMatrix.clone()
follow.update(fixed, inside, head, view, 1 / 60)
assert.equal(follow.active, false)
const inherited = follow.update(fixed, outside, head, view, 1 / 60)
assert.equal(follow.active, true)
assert.deepEqual(inherited.position.toArray(), fixed.position.toArray())
assert.deepEqual(inherited.quaternion.toArray(), fixed.quaternion.toArray())
assert.deepEqual(inherited.projectionMatrix.elements, fixed.projectionMatrix.elements)
follow.update(fixed, outside, head, view, 1 / 60)
assert(follow.offset.length() > 0 && follow.offset.length() < 1, 'handover must move gradually')
for (let frame = 0; frame < 180; frame++) follow.update(fixed, outside, head, view, 1 / 60)
const projected = head.clone().project(follow.camera)
assert(Math.abs(projected.x) < .501 && Math.abs(projected.y) < .501, 'head returns to central safe area')
assert.deepEqual(fixed.position.toArray(), originalPosition.toArray())
assert.deepEqual(fixed.projectionMatrix.elements, originalProjection.elements)
const beforeReturn = follow.offset.length()
follow.update(fixed, inside, head, view, 1 / 60)
assert.equal(follow.active, false)
assert(follow.offset.length() > 0 && follow.offset.length() < beforeReturn, 'zoom out returns smoothly')
for (let frame = 0; frame < 200; frame++) follow.update(fixed, inside, head, view, 1 / 60)
assert.equal(follow.offset.length(), 0)
follow.update(fixed, inside, null, { ...view, panX: 30 }, 1 / 60)
assert.equal(follow.active, true, 'panned field is checked in viewport coordinates')
follow.update(fixed, inside, null, view, 1 / 60, true)
assert.equal(follow.offset.length(), 0)
assert.equal(follow.active, false)
console.log('PASS: field clipping, exact camera handover, smooth following, unchanged fixed camera, smooth return and reset.')
