const fs = require('fs'), ts = require('typescript'), assert = require('node:assert/strict')
require.extensions['.ts'] = (module, file) => module._compile(ts.transpileModule(fs.readFileSync(file, 'utf8'), {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
}).outputText, file)
const { setSnakeHeadParams } = require('../src/engine/snake/snake.ts')
const { setFoodCoord } = require('../src/engine/food/food.ts')
const { getFoodOffset } = require('../src/engine/food/getFoodOffset.ts')
const { formatAppleOffset } = require('../src/assets/trainingArena/appleOffset.ts')
assert.equal(getFoodOffset(), null)
assert.equal(formatAppleOffset(null, false), '→ —\n↑ —')
const head = (x, y) => setSnakeHeadParams({ snakeHeadCoordX: x, snakeHeadCoordY: y, snakeHeadStepX: 1, snakeHeadStepY: 0 })
head(3, -2); setFoodCoord([15, -7])
assert.deepEqual(getFoodOffset(), { x: 12, y: -5 })
assert.equal(formatAppleOffset(getFoodOffset(), false), '→ +12\n↑ −5')
assert.equal(formatAppleOffset(getFoodOffset(), true), '→ −5\n↑ −12')
head(4, -2)
assert.equal(formatAppleOffset(getFoodOffset(), false), '→ +11\n↑ −5')
setFoodCoord([-8, 6])
assert.equal(formatAppleOffset(getFoodOffset(), false), '→ −12\n↑ +8')
assert.equal(formatAppleOffset(getFoodOffset(), true), '→ +8\n↑ +12')
setFoodCoord([4, -2])
assert.equal(formatAppleOffset(getFoodOffset(), true), '→ 0\n↑ 0')
head(Infinity, 0)
assert.equal(getFoodOffset(), null)
console.log('PASS: grid-cell offsets, movement, new apple, signs, zero, clockwise rotation and unavailable state.')
