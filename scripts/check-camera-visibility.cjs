const fs = require('fs'), ts = require('typescript'), assert = require('node:assert/strict')
const THREE = require('three')
require.extensions['.ts'] = (module, file) => module._compile(ts.transpileModule(fs.readFileSync(file, 'utf8'), {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
}).outputText, file)
const { createCameraVisibilityCheck } = require('../src/assets/trainingArena/cameraVisibility.ts')
const { cropCameraToViewport } = require('../src/assets/trainingArena/viewportCamera.ts')
const visible = createCameraVisibilityCheck()
const camera = new THREE.PerspectiveCamera(90, 1, .1, 100)
camera.position.z = 10; camera.lookAt(0, 0, 0); camera.updateMatrixWorld(true)
const apple = new THREE.Mesh(new THREE.BoxGeometry(1, 1, 1), new THREE.MeshBasicMaterial())
const update = (x, y = 0, z = 0) => { apple.position.set(x, y, z); apple.updateMatrixWorld(true) }
assert(!visible(undefined, camera))
update(0); assert(visible(apple, camera))
update(12); assert(!visible(apple, camera))
update(10.2); assert(!visible(apple, camera), 'partial entry must keep guidance visible')
update(9); assert(!visible(apple, camera), 'keep arrows near the screen edge')
update(7); assert(visible(apple, camera), 'hide once centre clears the edge margin')
update(0, 0, 12); assert(!visible(apple, camera), 'behind camera')
const cropped = cropCameraToViewport(new THREE.PerspectiveCamera(), camera, 400, 400, 100, 100, 0, 0)
update(4); assert(!visible(apple, cropped))
update(2.7); assert(!visible(apple, cropped))
update(1.9); assert(visible(apple, cropped))
update(0); apple.visible = false; assert(!visible(apple, cropped))
apple.visible = true
const parent = new THREE.Group(); parent.add(apple); parent.visible = false
assert(!visible(apple, cropped))
parent.visible = true; parent.updateMatrixWorld(true); assert(visible(apple, cropped))
camera.position.x = 4; camera.updateMatrixWorld(true)
cropCameraToViewport(cropped, camera, 400, 400, 100, 100, 0, 0)
assert(!visible(apple, cropped), 'following camera can move apple out of view again')
update(4); assert(visible(apple, cropped))
apple.geometry.dispose(); apple.material.dispose()
console.log('PASS: centre visibility with edge margin, partial-entry rejection, cropped 400% viewport, hidden model/parent and moving camera.')
